/**
 * Writes evals/CASES.md: every eval case with what it tests and its answer key,
 * generated from the case files so the list never drifts from them.
 *
 *   npx tsx evals/catalog.ts
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { CASES as DRAFT_CASES, type ExpectedChange } from "./change-draft/cases";
import { SCENARIOS, truthOf } from "./inbox-summary/scenarios";
import { CASES as MONEY_CASES } from "./money-answer/cases";

const usd = (cents: number) => `$${(cents / 100).toLocaleString("en-US", { minimumFractionDigits: 2 })}`;
const cell = (text: string) => text.replace(/\|/gu, "\\|").replace(/\n/gu, " ");

function change(entry: ExpectedChange): string {
  const item = entry.itemId ?? "new item";
  if (entry.action === "remove") return `remove ${item}`;
  if (entry.action === "quantity") return `${item} → ${entry.quantity}`;
  return `${entry.action} ${item} → ${entry.productOptionId ?? "(no source yet)"} ×${entry.quantity}`;
}

function draftKey(testCase: (typeof DRAFT_CASES)[number]): string {
  const expected = testCase.expected;
  const parts: string[] = [];
  if (expected.outcome === "draft") parts.push((expected.changes ?? []).map(change).join("; "));
  else if (expected.outcome === "no_draft") parts.push(`no draft (${(expected.intents ?? []).join(" or ")})`);
  else if (expected.outcome === "cancel") parts.push("withdraw the draft");
  else parts.push("refused before any model call");
  if (expected.alternatives?.length) parts.push(`also right: ${expected.alternatives.map((set) => set.map(change).join("; ")).join(" / ")}`);
  if (expected.forbiddenItemIds?.length) parts.push(`must not touch ${expected.forbiddenItemIds.join(", ")}`);
  if (expected.forbiddenOptionIds?.length) parts.push(`must not choose ${expected.forbiddenOptionIds.join(", ")}`);
  if (expected.requiredClaims?.length) parts.push(`must say /${expected.requiredClaims.join("/, /")}/`);
  if (expected.forbiddenClaims?.length) parts.push("must not claim a payment result");
  return parts.join(" · ");
}

const lines: string[] = [
  "# Eval cases",
  "",
  "Generated by `npx tsx evals/catalog.ts` from the case files; edit those, not this list. All projects, people, suppliers, products and prices are fictional. Answer keys were written before any model answered; where a first dry run showed the grader rejecting correct wording (a negation such as 'no refund has been completed', or a phrasing it did not list), the grader's phrase lists were widened before the keys were frozen at `81c76ce`. Grader changes since then are in the git history and in [README.md](README.md#limits).",
  "",
  `## Change drafts (${DRAFT_CASES.length} cases)`,
  "",
  "A project chat ends with an @Coordinator request; the key is the change set a designer would agree with, compared by action, quote line, quantity and chosen supplier product. Cases marked ×3 run three times to measure stability.",
  "",
  "| Case | Group | What it tests | Answer key |",
  "| --- | --- | --- | --- |",
  ...DRAFT_CASES.map((testCase) => `| \`${testCase.id}\`${testCase.stability ? " ×3" : ""} | ${testCase.tags.join(", ")} | ${cell(testCase.title)} | ${cell(draftKey(testCase))} |`),
  "",
  `## Money answers (${MONEY_CASES.length} cases)`,
  "",
  "A question about recorded payments in the Maple project. The evidence was captured read-only from real local Sandbox walkthroughs (`money-answer/fixtures/`), or built by Setti's own V1 evidence builder. Setti's server checks every amount and status the answer writes; the key adds what the answer must say, must not claim and must cite.",
  "",
  "| Case | Group | What it tests | Answer key |",
  "| --- | --- | --- | --- |",
  ...MONEY_CASES.map((testCase) => {
    const expected = testCase.expected;
    const key = [
      ...(expected.requiredClaims ?? []).map((claim) => `must say /${claim}/`),
      ...(expected.forbiddenClaims?.length ? ["must not claim a refund or charge the records do not show"] : []),
      ...(expected.mustCite?.length ? [`cites ${expected.mustCite.join(", ")}`] : []),
      ...(expected.showEvidence !== undefined ? [`shows the records: ${expected.showEvidence}`] : []),
      ...(expected.minRows ? [`at least ${expected.minRows} item rows`] : []),
    ].join(" · ");
    return `| \`${testCase.id}\`${testCase.stability ? " ×3" : ""} | ${testCase.tags.join(", ")} | ${cell(testCase.title)} | ${cell(key)} |`;
  }),
  "",
  `## Client inbox summaries (${SCENARIOS.length} scenarios)`,
  "",
  "A timeline of holds, charges, releases and refunds goes through the inbox's own fact builder. The grader works out from the timeline alone what is on hold now, and fails any clause that states something else as on hold today.",
  "",
  "| Scenario | What it tests | On hold now (truth) |",
  "| --- | --- | --- |",
  ...SCENARIOS.map((scenario) => {
    const truth = truthOf(scenario.timeline());
    const held = truth.items.filter((item) => item.heldCents > 0).map((item) => `${item.label} ${usd(item.heldCents)}`).join(", ") || "nothing";
    return `| \`${scenario.id}\` | ${cell(scenario.title)} | ${usd(truth.heldCents)}: ${cell(held)} |`;
  }),
  "",
];
writeFileSync(join(process.cwd(), "evals", "CASES.md"), `${lines.join("\n")}`);
console.log(`wrote evals/CASES.md · ${DRAFT_CASES.length} change drafts, ${MONEY_CASES.length} money answers, ${SCENARIOS.length} inbox scenarios`);
